// Writes src/font_tables.inc: the tables reading font programs needs, taken from their
// sources so they are exact:
//   - the Adobe Glyph List (glyph name to Unicode), from Adobe's glyphlist.txt (Apache-2.0,
//     its notice kept in the output);
//   - the CFF standard strings, the standard, WinAnsi, MacRoman, MacExpert, Symbol and
//     ZapfDingbats encodings and the 258 standard Macintosh glyph names, as pdf.js has them
//     (Apache-2.0).
//
// Run in the bench container, which has both (from the repository's root):
//   ./bench/bench.sh node --input-type=module - \
//     /usr/share/texlive/texmf-dist/fonts/map/glyphlist/glyphlist.txt \
//     /opt/deps/node_modules/pdfjs-dist/build/pdf.worker.mjs \
//     < scripts/make-font-tables.mjs > src/font_tables.inc

import fs from "node:fs";

const [glyphlistFile, workerFile] = process.argv.slice(2);
const glyphlist = fs.readFileSync(glyphlistFile, "utf8");
const worker = fs.readFileSync(workerFile, "utf8");

// An array literal assigned to |name| in pdf.js's worker, evaluated.
function array(name) {
  const at = worker.search(new RegExp(`(?:const|var|let)\\s+${name}\\s*=\\s*\\[`));
  if (at < 0) throw new Error(`no ${name} in pdf.js`);
  const start = worker.indexOf("[", at);
  let depth = 0;
  for (let i = start; i < worker.length; i++) {
    if (worker[i] === "[") depth++;
    else if (worker[i] === "]" && --depth === 0) return Function(`return ${worker.slice(start, i + 1)}`)();
  }
  throw new Error(`unterminated ${name}`);
}

const quote = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const lines = [];
lines.push("// Generated by scripts/make-font-tables.mjs; do not edit.");
lines.push("//");
lines.push("// The Adobe Glyph List is from Adobe's glyphlist.txt, under this notice:");
for (const line of glyphlist.split("\n")) {
  if (!line.startsWith("#")) break;
  lines.push(`//${line.slice(1)}`.trimEnd());
  if (line.startsWith("# URL:")) break;
}
lines.push("//");
lines.push("// The other tables are as pdf.js (Apache-2.0) has them.");
lines.push("");

// Glyph name to Unicode (the first code point of each entry), sorted by name for binary search.
const agl = [];
for (const line of glyphlist.split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [name, codes] = line.split(";");
  agl.push([name, parseInt(codes.trim().split(" ")[0], 16)]);
}
agl.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
lines.push("struct GlyphUnicode {");
lines.push("  const char *name;");
lines.push("  unsigned code;");
lines.push("};");
lines.push(`const GlyphUnicode kGlyphList[${agl.length}] = {`);
for (let i = 0; i < agl.length; i += 4)
  lines.push("    " + agl.slice(i, i + 4).map(([n, c]) => `{${quote(n)}, 0x${c.toString(16).padStart(4, "0")}}`).join(", ") + ",");
lines.push("};");
lines.push("");

const names = (cName, jsName, length) => {
  const values = array(jsName);
  if (length && values.length !== length) throw new Error(`${jsName}: ${values.length} entries, expected ${length}`);
  lines.push(`const char *const ${cName}[${values.length}] = {`);
  for (let i = 0; i < values.length; i += 8) lines.push("    " + values.slice(i, i + 8).map((v) => quote(v || "")).join(", ") + ",");
  lines.push("};");
  lines.push("");
};
// A getLookupTableFactory(function (t) { t.name = value; ... }) table from |start| on, as
// [name, value] pairs sorted by name.
function lookup(start) {
  const open = worker.indexOf("function (t) {", start);
  let depth = 0;
  let end = open;
  for (let i = worker.indexOf("{", open); i < worker.length; i++) {
    if (worker[i] === "{") depth++;
    else if (worker[i] === "}" && --depth === 0) {
      end = i;
      break;
    }
  }
  const body = worker.slice(open, end);
  const pairs = [];
  for (const m of body.matchAll(/t(?:\.([A-Za-z_$][\w$]*)|\["([^"]+)"\])\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;/g))
    pairs.push([m[1] ?? m[2], Number(m[3])]);
  return pairs.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
}
const table = (cName, type, pairs, hex) => {
  lines.push(`const ${type} ${cName}[${pairs.length}] = {`);
  for (let i = 0; i < pairs.length; i += 4)
    lines.push("    " + pairs.slice(i, i + 4).map(([n, v]) => `{${quote(n)}, ${hex ? `0x${v.toString(16).padStart(4, "0")}` : v}}`).join(", ") + ",");
  lines.push("};");
  lines.push("");
};
// ITC Zapf Dingbats glyph names (a1, a2, ...) to Unicode.
table("kDingbatsList", "GlyphUnicode", lookup(worker.indexOf("const getDingbatsGlyphsUnicode")), true);
// The standard 14 Symbol and ZapfDingbats fonts' widths by glyph name (Adobe's AFM files), for
// PDFs that name them with no widths of their own.
lines.push("struct GlyphWidth {");
lines.push("  const char *name;");
lines.push("  int width;");
lines.push("};");
const metrics = worker.indexOf("const getMetrics");
table("kSymbolWidths", "GlyphWidth", lookup(worker.indexOf("t.Symbol = getLookupTableFactory", metrics)), false);
table("kDingbatsWidths", "GlyphWidth", lookup(worker.indexOf("t.ZapfDingbats = getLookupTableFactory", metrics)), false);
names("kCffStandardStrings", "CFFStandardStrings", 391);
names("kStandardEncoding", "StandardEncoding", 256);
names("kWinAnsiEncoding", "WinAnsiEncoding", 256);
names("kMacRomanEncoding", "MacRomanEncoding", 256);
names("kMacExpertEncoding", "MacExpertEncoding", 256);
names("kSymbolEncoding", "SymbolSetEncoding", 256);
names("kZapfDingbatsEncoding", "ZapfDingbatsEncoding", 256);
names("kMacGlyphNames", "MacStandardGlyphOrdering", 258);
process.stdout.write(lines.join("\n"));
